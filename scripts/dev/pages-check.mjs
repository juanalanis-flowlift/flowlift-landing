// Pruebas de las páginas internas: precios por periodo, tabla accesible, buscador de preguntas. Uso: node scripts/dev/pages-check.mjs [puerto]
import { createRequire } from 'node:module'
const { chromium } = createRequire(import.meta.url)('playwright')
const base = `http://127.0.0.1:${process.argv[2] || 4173}`
const b = await chromium.launch()
const out = (ok, m) => console.log((ok ? '✓ ' : '✗ ') + m)
const p = await b.newPage({ viewport: { width: 1280, height: 900 } })
await p.goto(base + '/precios', { waitUntil: 'networkidle' })
const prices = async () => (await p.locator('.pr-page .price').allInnerTexts()).map((t) => t.replace(/\s+/g, ' ').trim())
out(JSON.stringify(await prices()) === JSON.stringify(['Gratis para siempre', '$349 MXN/mes', '$649 MXN/mes']), 'mensual: ' + (await prices()).join(' | '))
await p.getByRole('tab', { name: /Anual/ }).click()
out(JSON.stringify(await prices()) === JSON.stringify(['Gratis para siempre', '$3,499 MXN/año', '$6,490 MXN/año']), 'anual: ' + (await prices()).join(' | '))
await p.getByRole('tab', { name: /Trimestral/ }).focus(); await p.keyboard.press('Enter')
out(JSON.stringify(await prices()) === JSON.stringify(['Gratis para siempre', '$945 MXN/trim.', '$1,750 MXN/trim.']), 'trimestral OXXO: ' + (await prices()).join(' | '))
await p.keyboard.press('ArrowLeft')
out((await p.locator('[role=tab][aria-selected=true]').innerText()).startsWith('Anual'), 'flecha izquierda cambia de pestaña')
out(await p.locator('table.tbl th[scope=row]').count() === 24, 'tabla: 24 filas con th[scope=row] (' + await p.locator('table.tbl th[scope=row]').count() + ')')
out(await p.locator('table.tbl .sr').count() > 40, 'tabla: celdas con texto accesible (Incluido / No incluido)')
await p.goto(base + '/en/pricing', { waitUntil: 'networkidle' })
await p.getByRole('tab', { name: /Annual/ }).click()
out((await p.locator('.pr-page .price').allInnerTexts()).join('|').includes('$3,499'), 'EN anual $3,499')
// FAQ
await p.goto(base + '/preguntas-frecuentes', { waitUntil: 'networkidle' })
out(await p.locator('.faqp-cat').count() === 10 && await p.locator('.faq-q').count() === 43, 'FAQ: 10 categorías y 43 preguntas')
await p.fill('input[type=search]', 'politica de cancelacion')
await p.waitForTimeout(300)
const n = await p.locator('.faq-q').count()
out(n >= 1 && n < 10, `buscar "politica de cancelacion" (sin acentos) → ${n} resultado(s); abiertas: ${await p.locator('.faq-a').count()}`)
out((await p.locator('[role=status]').innerText()).includes('encontrad'), 'anuncio de resultados: ' + (await p.locator('[role=status]').innerText()))
await p.fill('input[type=search]', 'zzzzxq'); await p.waitForTimeout(300)
out((await p.locator('.faqp-none').innerText()).startsWith('No encontramos'), 'sin resultados muestra mensaje')
await p.fill('input[type=search]', ''); await p.waitForTimeout(200)
await p.locator('.faqp-index a').nth(2).click(); await p.waitForTimeout(500)
out(p.url().endsWith('#c3'), 'índice de categorías navega a ' + p.url().split('/').pop())
// Ayuda
await p.goto(base + '/ayuda', { waitUntil: 'networkidle' })
out(await p.locator('.help-q').count() === 65, 'Ayuda: 65 artículos en 11 secciones (' + await p.locator('.help-q').count() + ' / ' + await p.locator('section.help-sec').count() + ')')
const q1 = p.locator('.help-q').first(); await q1.click()
out((await q1.getAttribute('aria-expanded')) === 'true' && await p.locator('.help-body').count() === 1, 'abrir un artículo con clic')
await p.goto(base + '/ayuda#article-logo', { waitUntil: 'networkidle' }); await p.waitForTimeout(400)
out(await p.locator('#article-logo .help-body').count() === 1, 'el enlace #article-logo abre ese artículo')
await p.fill('input[type=search]', 'recordatorios'); await p.waitForTimeout(300)
const nA = await p.locator('.help-q').count()
out(nA > 0 && nA < 65 && await p.locator('.help-body').count() === nA, `buscar "recordatorios" → ${nA} artículos, todos abiertos`)
await p.fill('input[type=search]', ''); await p.locator('a.chip', { hasText: /^recordatorios$/ }).click(); await p.waitForTimeout(400)
out(p.url().endsWith('#section-notifications-reminders'), 'búsqueda popular lleva a su sección (' + p.url().split('#')[1] + ')')
// Legales
await p.goto(base + '/politica-de-privacidad', { waitUntil: 'networkidle' })
out(await p.locator('.doc-sec').count() === 13 && await p.locator('.doc-simple').count() === 13, 'Privacidad: 13 secciones con resumen "En simple"')
out(await p.locator('.doc-tbl table').count() >= 1, 'Privacidad: tabla de proveedores como <table> con encabezados')
await p.goto(base + '/en/terms-and-conditions', { waitUntil: 'networkidle' })
out(await p.locator('.doc-sec').count() === 19 && await p.locator('#anexo').count() === 1, 'Términos (EN): 18 secciones + anexo')
await p.locator('.doc-toc a').nth(5).click(); await p.waitForTimeout(300)
out(p.url().endsWith('#s6'), 'índice lleva a ' + p.url().split('/').pop())
await b.close()
